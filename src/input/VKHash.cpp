bool bIsReservedVK(int vk) {
  return vk == 0x07 || (vk >= 0x0A && vk <= 0x0B) || (vk >= 0x0E && vk <= 0x0F) || (vk >= 0x3A && vk <= 0x40) || vk == 0x5E || (vk >= 0x88 && vk <= 0x8F) ||
         (vk >= 0x97 && vk <= 0x9F) || (vk >= 0xB8 && vk <= 0xB9) || (vk >= 0xC1 && vk <= 0xC2) || (vk >= 0xD8 && vk <= 0xDA) || vk == 0xE0 || vk == 0xE8;
}
